"""Generate the documentation page from machine-readable verification reports."""

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
from xml.etree import ElementTree


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--junit", type=Path, required=True)
    parser.add_argument("--coverage", type=Path, required=True)
    parser.add_argument("--frontend", type=Path)
    parser.add_argument("--output", type=Path, default=Path("docs/quality/test-results.md"))
    args = parser.parse_args()
    suites = ElementTree.parse(args.junit).getroot()
    cases = list(suites.iter("testcase"))
    failed = sum(
        case.find("failure") is not None or case.find("error") is not None for case in cases
    )
    skipped = sum(case.find("skipped") is not None for case in cases)
    coverage = json.loads(args.coverage.read_text(encoding="utf-8"))
    timestamp = next(
        (suite.get("timestamp") for suite in suites.iter("testsuite") if suite.get("timestamp")),
        datetime.now(timezone.utc).isoformat(),
    )
    lines = [
        "# Tests and Results",
        "",
        "This page is generated by scripts/report_test_results.py from test reports.",
        "CI regenerates it after verification; the date and counts below describe that run only.",
        "",
        f"Report timestamp: {timestamp}.",
        "",
        "| Check | Result |",
        "| --- | --- |",
        f"| Python tests | {len(cases) - failed - skipped} passed, "
        f"{failed} failed, {skipped} skipped |",
        f"| Overall Python coverage | {coverage['totals']['percent_covered']:.2f}% |",
    ]
    for module in ("manager", "tracking", "worker"):
        match = next(
            (
                value
                for name, value in coverage["files"].items()
                if name.replace("\\", "/").endswith(f"pspso/dashboard/{module}.py")
            ),
            None,
        )
        if match:
            lines.append(
                f"| {module.capitalize()} coverage | {match['summary']['percent_covered']:.2f}% |"
            )
    if args.frontend:
        frontend = json.loads(args.frontend.read_text(encoding="utf-8"))
        lines.append(
            f"| Frontend tests | {frontend['numPassedTests']} passed, "
            f"{frontend['numFailedTests']} failed |"
        )
    lines += [
        "",
        "The release gates require at least 80% overall coverage and at least 90% for",
        "the manager, tracking repository and worker. Optional model jobs perform actual",
        "training, prediction and model serialization for the installed backend.",
        "",
        "The CI workflow also checks typing, formatting, frontend production builds,",
        "browser workflows, documentation, dependency audits and installation from the wheel.",
        "Those checks are separate gates; passing test counts alone do not prove them.",
        "",
        "## Test groups",
        "",
    ]
    groups = {}
    for case in cases:
        name = case.get("classname", "unknown")
        groups[name] = groups.get(name, 0) + 1
    lines += ["| Group | Cases |", "| --- | --- |"]
    lines += [f"| {name} | {count} |" for name, count in sorted(groups.items())]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
